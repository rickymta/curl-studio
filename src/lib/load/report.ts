/** Load-test report exports: self-contained HTML (same charts as the app), CSV, JUnit, Markdown. */
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

import { fromRun, ReportBody, setReportEnglish } from '@/features/load/RunReport';

import { formatBytes, formatDuration, formatMs, formatNum, formatPct } from '../format';
import type { RunRecord, Summary } from './types';

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);

/** All CSS rules currently loaded (Tailwind output + tokens), inlined into the report. */
function collectCss(): string {
  let css = '';
  for (const sheet of Array.from(document.styleSheets)) {
    try {
      for (const rule of Array.from(sheet.cssRules)) css += `${rule.cssText}\n`;
    } catch {
      /* cross-origin sheet */
    }
  }
  return css;
}

export function htmlReport(run: RunRecord, theme: 'light' | 'dark' = 'light'): string {
  const d = fromRun(run);
  const s = run.summary;
  // Exported reports stay English whatever the app language is.
  let body: string;
  setReportEnglish(true);
  try {
    body = renderToStaticMarkup(createElement(ReportBody, { d, staticWidth: 1180 }));
  } finally {
    setReportEnglish(false);
  }
  const verdict = s.verdict === 'passed';
  const sc = run.scenario;
  const profile =
    sc?.profile.executor === 'iterations'
      ? `${sc.profile.vus} VUs × ${sc.profile.iterations} shared iterations`
      : sc?.profile.executor === 'arrivalRate'
        ? `Arrival rate: ${sc.profile.startRate} → ${sc.profile.stages.map((x) => `${x.target}/${sc.profile.executor === 'arrivalRate' ? sc.profile.timeUnitS : 1}s over ${x.durationS}s`).join(' → ')} (max ${sc.profile.maxVus} VUs)`
        : sc
          ? `Ramping VUs: ${sc.profile.startVus} → ${sc.profile.stages.map((x) => `${x.target} over ${x.durationS}s`).join(' → ')}`
          : '';
  return `<!doctype html>
<html lang="en" class="${theme === 'dark' ? 'dark' : ''}">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${esc(/load test/i.test(run.name) ? run.name : `${run.name} – load test`)} report</title>
<style>${collectCss()}
body { overflow: auto !important; user-select: text !important; background: var(--background); }
.report { max-width: 1240px; margin: 0 auto; padding: 24px; }
.toolbar button { border: 1px solid var(--border); border-radius: 6px; padding: 2px 10px; background: var(--surface); color: var(--foreground); cursor: pointer; }
@media print { .toolbar { display: none; } .chart-card { break-inside: avoid; } }
</style>
</head>
<body>
<div class="report">
  <header style="display:flex;gap:16px;align-items:flex-start;margin-bottom:16px">
    <div style="flex:1">
      <div style="font-size:12px;color:var(--muted-foreground)">CurlStudio load test report</div>
      <h1 style="font-size:22px;font-weight:700;margin:2px 0">${esc(run.name)}</h1>
      <div style="font-size:12px;color:var(--muted-foreground)">
        ${esc(new Date(run.startedAt).toLocaleString())} · ${formatDuration(s.durationS)} · ${esc(run.meta?.testType ?? '')} ${run.meta?.environment ? `· env ${esc(run.meta.environment)}` : ''}<br/>
        ${esc(profile)}${run.reason ? ` · <b>${esc(run.reason)}</b>` : ''}
      </div>
      ${run.meta?.notes ? `<p style="margin-top:8px;font-size:13px">${esc(run.meta.notes)}</p>` : ''}
    </div>
    <div style="text-align:right">
      <div style="display:inline-block;padding:6px 14px;border-radius:8px;font-weight:700;font-size:16px;background:${verdict ? 'var(--success-soft)' : 'var(--danger-soft)'};color:${verdict ? 'var(--success)' : 'var(--danger)'}">${verdict ? 'PASSED' : 'FAILED'}</div>
      <div class="toolbar" style="margin-top:8px"><button onclick="document.documentElement.classList.toggle('dark')">Toggle theme</button> <button onclick="print()">Print / PDF</button></div>
    </div>
  </header>
  ${body}
  <footer style="margin-top:24px;font-size:11px;color:var(--muted-foreground)">Generated by CurlStudio · run ${esc(run.id)}</footer>
</div>
</body>
</html>`;
}

const csvCell = (v: unknown) => {
  const s = String(v ?? '');
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
const csv = (rows: unknown[][]) => rows.map((r) => r.map(csvCell).join(',')).join('\n');

export function timelineCsv(run: RunRecord): string {
  const codes = [...new Set(run.timeline.flatMap((p) => Object.keys(p.status)))].sort();
  return csv([
    ['second', 'vus', 'requests', 'failures', 'iterations', 'dropped', 'avg_ms', 'min_ms', 'p50_ms', 'p90_ms', 'p95_ms', 'p99_ms', 'max_ms', 'ttfb_avg_ms', 'bytes_in', 'bytes_out', 'checks_pass', 'checks_fail', 'apdex', ...codes.map((c) => `status_${c}`)],
    ...run.timeline.map((p) => [p.t, p.vus, p.requests, p.failures, p.iterations, p.dropped, p.avg.toFixed(2), p.min.toFixed(2), p.p50.toFixed(2), p.p90.toFixed(2), p.p95.toFixed(2), p.p99.toFixed(2), p.max.toFixed(2), p.waitAvg.toFixed(2), p.bytesIn, p.bytesOut, p.checksPass, p.checksFail, p.apdex?.toFixed(3) ?? '', ...codes.map((c) => p.status[c] ?? 0)]),
  ]);
}

export function aggregateCsv(s: Summary): string {
  const rows: unknown[][] = [['label', 'method', 'url', 'samples', 'avg_ms', 'median_ms', 'p90_ms', 'p95_ms', 'p99_ms', 'min_ms', 'max_ms', 'stddev_ms', 'error_pct', 'throughput_rps', 'received_kb_s', 'sent_kb_s', 'apdex']];
  const d = Math.max(s.durationS, 0.001);
  for (const st of s.steps) {
    const l = st.latency;
    rows.push([st.name, st.method, st.url, st.count, l.avg.toFixed(2), l.p50.toFixed(2), l.p90.toFixed(2), l.p95.toFixed(2), l.p99.toFixed(2), l.min.toFixed(2), l.max.toFixed(2), l.stddev.toFixed(2), (st.errorRate * 100).toFixed(3), st.rps.toFixed(3), (st.bytesIn / 1024 / d).toFixed(2), (st.bytesOut / 1024 / d).toFixed(2), st.apdex.toFixed(3)]);
  }
  const l = s.latency;
  rows.push(['TOTAL', '', '', s.requests, l.avg.toFixed(2), l.p50.toFixed(2), l.p90.toFixed(2), l.p95.toFixed(2), l.p99.toFixed(2), l.min.toFixed(2), l.max.toFixed(2), l.stddev.toFixed(2), (s.errorRate * 100).toFixed(3), s.rps.toFixed(3), (s.bytesIn / 1024 / d).toFixed(2), (s.bytesOut / 1024 / d).toFixed(2), s.apdex.score.toFixed(3)]);
  return csv(rows);
}

/** JUnit XML for CI: thresholds and checks as test cases. */
export function junitXml(run: RunRecord): string {
  const s = run.summary;
  const cases: string[] = [];
  let failures = 0;
  for (const t of s.thresholds) {
    const name = esc(t.expression);
    if (t.pass) cases.push(`    <testcase classname="thresholds" name="${name}" />`);
    else {
      failures++;
      cases.push(`    <testcase classname="thresholds" name="${name}"><failure message="actual ${t.actual ?? 'n/a'}">${name} — actual ${t.actual ?? 'n/a'}</failure></testcase>`);
    }
  }
  const names = Object.fromEntries((run.scenario?.steps ?? []).map((x) => [x.id, x.name]));
  for (const c of s.checks) {
    const name = esc(`${names[c.step] ?? c.step}: ${c.name}`);
    if (!c.fail) cases.push(`    <testcase classname="checks" name="${name}" />`);
    else {
      failures++;
      cases.push(`    <testcase classname="checks" name="${name}"><failure message="${c.fail} of ${c.pass + c.fail} failed" /></testcase>`);
    }
  }
  return `<?xml version="1.0" encoding="UTF-8"?>
<testsuites name="${esc(run.name)}" tests="${cases.length}" failures="${failures}" time="${s.durationS.toFixed(1)}">
  <testsuite name="${esc(run.name)}" tests="${cases.length}" failures="${failures}" time="${s.durationS.toFixed(1)}" timestamp="${run.startedAt}">
${cases.join('\n')}
  </testsuite>
</testsuites>
`;
}

/** Markdown summary (PR comments, chat). */
export function markdownSummary(run: RunRecord): string {
  const s = run.summary;
  const lines = [
    `## ${s.verdict === 'passed' ? '✅' : '❌'} ${run.name}`,
    '',
    `${new Date(run.startedAt).toLocaleString()} · ${formatDuration(s.durationS)} · max ${s.vusMax} VUs`,
    '',
    '| Metric | Value |',
    '|---|---|',
    `| Requests | ${formatNum(s.requests)} (${formatNum(s.rps, 1)}/s, peak ${s.peakRps}/s) |`,
    `| Error rate | ${formatPct(s.errorRate)} |`,
    `| Latency avg / p50 / p95 / p99 | ${formatMs(s.latency.avg)} / ${formatMs(s.latency.p50)} / ${formatMs(s.latency.p95)} / ${formatMs(s.latency.p99)} |`,
    `| Apdex (T=${s.apdex.tMs} ms) | ${s.apdex.score.toFixed(2)} |`,
    `| Checks | ${formatPct(s.checksPass / Math.max(1, s.checksPass + s.checksFail))} |`,
    `| Data | ↓ ${formatBytes(s.bytesIn)} ↑ ${formatBytes(s.bytesOut)} |`,
    '',
  ];
  if (s.thresholds.length) {
    lines.push('### Thresholds', '', ...s.thresholds.map((t) => `- ${t.pass ? '✅' : '❌'} \`${t.expression}\` — actual ${t.actual === null ? 'n/a' : +t.actual.toFixed(3)}`), '');
  }
  lines.push('### Requests', '', '| Request | Samples | p95 | Error % | RPS |', '|---|---:|---:|---:|---:|');
  for (const st of s.steps) lines.push(`| ${st.method} ${st.name} | ${st.count} | ${formatMs(st.latency.p95)} | ${formatPct(st.errorRate)} | ${st.rps.toFixed(1)} |`);
  return lines.join('\n');
}
